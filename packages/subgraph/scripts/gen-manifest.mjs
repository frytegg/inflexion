#!/usr/bin/env node
/**
 * Generate `subgraph.yaml` from `deployments/arbitrum-sepolia.json` — the SINGLE
 * source of truth for every on-chain address (CLAUDE.md hard rule: never hardcode
 * an address). This is the same registry the SDK's `addresses.ts` consumes.
 *
 * IMPORTANT — the moat dataset begins at the single redeploy. The rich data-moat
 * events (`QuoteFilled` / `SwapPriced`) are CODED but NOT live until then; this
 * manifest is REGENERATED at that redeploy with the redeploy block as `startBlock`,
 * and the moat time-series begins there. Pre-redeploy those handlers simply never
 * fire (the entities exist, ready). Set the start block via env:
 *
 *   SUBGRAPH_START_BLOCK=<deployBlock> node scripts/gen-manifest.mjs
 *
 * The committed default is 0 (index from genesis — safe but slow); CI only runs
 * `graph codegen`, which validates schema+ABIs+mappings offline and does NOT need
 * a real startBlock. The full WASM build/deploy (`build:wasm`/`deploy`) is for the
 * home PC, where the redeploy block is plugged in.
 *
 * Offline + deterministic: reads the JSON, writes YAML, no network.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, '..', '..', '..')
const registryPath = join(repoRoot, 'deployments', 'arbitrum-sepolia.json')
const outPath = join(__dirname, '..', 'subgraph.yaml')

const reg = JSON.parse(readFileSync(registryPath, 'utf8'))

const network = 'arbitrum-sepolia'
const startBlock = Number(process.env.SUBGRAPH_START_BLOCK ?? '0')

const core = reg.deployment.core.inflexionCore
const convexityVault = reg.deployment.core.convexityVault
const volOracle = reg.deployment.core.volOracle

// graph-cli expects lowercase 0x addresses in the manifest.
const lc = (a) => String(a).toLowerCase()

const yaml = `# AUTO-GENERATED by scripts/gen-manifest.mjs — DO NOT EDIT BY HAND.
# Templated from deployments/arbitrum-sepolia.json (the single address registry).
#
# Regenerated at the single redeploy with the redeploy block as startBlock — the
# moat dataset BEGINS there. The rich events (QuoteFilled / SwapPriced) are coded
# but do not fire until the redeploy; pre-redeploy their handlers are simply idle.
#
# Re-run:  SUBGRAPH_START_BLOCK=<deployBlock> pnpm prepare:manifest
specVersion: 0.0.5
description: Inflexion — in-range IL convexity hedge indexer (the five data-moat signals).
schema:
  file: ./schema.graphql
dataSources:
  - kind: ethereum
    name: InflexionCore
    network: ${network}
    source:
      address: "${lc(core)}"
      abi: InflexionCore
      startBlock: ${startBlock}
    mapping:
      kind: ethereum/events
      apiVersion: 0.0.7
      language: wasm/assemblyscript
      file: ./src/inflexion-core.ts
      entities:
        - Market
        - Swap
        - BucketAggregate
        - GeometryDemandBucket
        - NetGammaSnapshot
        - ProtocolState
        - MarketMaker
        - MarketStateSnapshot
        - SigmaPoint
        - Nonce
      abis:
        - name: InflexionCore
          file: ./abis/InflexionCore.json
        - name: NonfungiblePositionManager
          file: ./abis/NonfungiblePositionManager.json
      eventHandlers:
        - event: MarketRegistered(indexed bytes32,address,address,uint24,uint32,address)
          handler: handleMarketRegistered
        - event: MarketDeactivated(indexed bytes32)
          handler: handleMarketDeactivated
        - event: TreasurySet(indexed address)
          handler: handleTreasurySet
        - event: CvammConfigured(address,address,address)
          handler: handleCvammConfigured
        - event: CvammFrozen()
          handler: handleCvammFrozen
        - event: CvammEnabledSet(indexed bytes32,bool)
          handler: handleCvammEnabledSet
        - event: LoadParamsSet()
          handler: handleLoadParamsSet
        - event: SwapCreated(indexed uint256,indexed address,indexed address,uint256,uint128,uint128,uint128)
          handler: handleSwapCreated
        - event: SwapPriced(indexed uint256,uint8,uint256,uint256,uint256,uint256,uint256,uint256,bool)
          handler: handleSwapPriced
        - event: QuoteFilled(indexed uint256,indexed address,indexed bytes32,uint256,uint16)
          handler: handleQuoteFilled
        - event: SwapRouted(indexed uint256,bool,uint256,uint256)
          handler: handleSwapRouted
        - event: SwapSettled(indexed uint256,uint256,uint128,uint256)
          handler: handleSwapSettled
        - event: NoncesCancelled(indexed address,uint256[])
          handler: handleNoncesCancelled
  - kind: ethereum
    name: ConvexityVault
    network: ${network}
    source:
      address: "${lc(convexityVault)}"
      abi: ConvexityVault
      startBlock: ${startBlock}
    mapping:
      kind: ethereum/events
      apiVersion: 0.0.7
      language: wasm/assemblyscript
      file: ./src/convexity-vault.ts
      entities:
        - Depositor
        - PoolState
        - PoolDaySnapshot
        - PoolHourSnapshot
      abis:
        - name: ConvexityVault
          file: ./abis/ConvexityVault.json
      eventHandlers:
        - event: Deposited(indexed address,indexed uint8,uint256,uint256)
          handler: handleDeposited
        - event: WithdrawRequested(indexed address,indexed uint8,uint256,uint64)
          handler: handleWithdrawRequested
        - event: Withdrawn(indexed address,indexed uint8,uint256,uint256)
          handler: handleWithdrawn
        - event: PremiumAccrued(uint256,uint256,uint256)
          handler: handlePremiumAccrued
        - event: CollateralLocked(indexed bytes32,uint256,uint256)
          handler: handleCollateralLocked
        - event: SettlementReleased(indexed bytes32,indexed address,uint256,uint256)
          handler: handleSettlementReleased
        - event: JuniorLoss(uint256,uint256,uint256)
          handler: handleJuniorLoss
  - kind: ethereum
    name: VolOracle
    network: ${network}
    source:
      address: "${lc(volOracle)}"
      abi: VolOracle
      startBlock: ${startBlock}
    mapping:
      kind: ethereum/events
      apiVersion: 0.0.7
      language: wasm/assemblyscript
      file: ./src/vol-oracle.ts
      entities:
        - SigmaPoint
      abis:
        - name: VolOracle
          file: ./abis/VolOracle.json
      eventHandlers:
        - event: Poked(indexed address,uint256,uint256,uint256,uint256)
          handler: handlePoked
        - event: Initialized(indexed address,uint256,uint256)
          handler: handleInitialized
`

writeFileSync(outPath, yaml)
console.log(
  `subgraph.yaml generated (network=${network}, startBlock=${startBlock}) from ${registryPath}`,
)
